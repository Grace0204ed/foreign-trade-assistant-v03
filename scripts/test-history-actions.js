const assert=require('node:assert/strict'),D=require('better-sqlite3');
const {changeHistory}=require('../server/history-actions');
const db=new D(':memory:');
db.exec(`CREATE TABLE quotations(id TEXT PRIMARY KEY,status TEXT,is_formal INTEGER,updated_at TEXT);
CREATE TABLE quote_versions(id TEXT PRIMARY KEY,status TEXT,is_formal INTEGER,updated_at TEXT);
CREATE TABLE audit_logs(id TEXT,user_id TEXT,action TEXT,entity_type TEXT,entity_id TEXT,before_json TEXT,after_json TEXT,reason TEXT,created_at TEXT);
INSERT INTO quotations VALUES('draft','Draft',0,''),('formal','Formal',1,''),('void','Void',1,'');
INSERT INTO quote_versions VALUES('vehicle','Formal',1,'');`);
const entries=[{type:'standard',id:'draft'},{type:'standard',id:'formal'},{type:'vehicle',id:'vehicle'}];
assert.equal(changeHistory(db,entries,'delete'),3);
assert.equal(db.prepare("SELECT COUNT(*) n FROM quotations WHERE status='Deleted'").get().n,2);
assert.equal(db.prepare('SELECT COUNT(*) n FROM quotations').get().n,3,'soft delete preserves originals');
changeHistory(db,entries,'restore');
assert.equal(db.prepare("SELECT status FROM quotations WHERE id='formal'").get().status,'Formal');
changeHistory(db,[{type:'standard',id:'void'}],'delete');changeHistory(db,[{type:'standard',id:'void'}],'restore');
assert.equal(db.prepare("SELECT status FROM quotations WHERE id='void'").get().status,'Void','restoring a void record must not reactivate it');
assert.throws(()=>changeHistory(db,[entries[0],{type:'standard',id:'missing'}],'delete'));
assert.equal(db.prepare("SELECT status FROM quotations WHERE id='draft'").get().status,'Draft','batch rollback is atomic');
changeHistory(db,[entries[0]],'void');
assert.equal(db.prepare("SELECT status FROM quotations WHERE id='draft'").get().status,'Void');
console.log('Passed mixed bulk deletion, restore, void, audit and atomic rollback using isolated in-memory database.');
db.close();
