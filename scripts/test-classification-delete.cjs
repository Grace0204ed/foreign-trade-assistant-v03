const {app}=require('electron');
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
process.env.QUOTE_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'fta-delete-classification-'));
app.whenReady().then(async()=>{
 const {db}=require('../server/db'),model=require('../assets/product-hierarchy');
 const {createClassificationDeletion}=require('../server/classification-delete');
 const insert=db.prepare('INSERT INTO products (id,category,brand,model,values_json,created_at,updated_at) VALUES (?,?,?,?,?,?,?)');
 const fixtures=[{id:'keep',category:'挖掘机',brand:'CAT',model:'320'},{id:'remove',category:'未分类资料',brand:'OTHER',model:'X'}];
 fixtures.forEach(p=>insert.run(p.id,p.category,p.brand,p.model,'{}','test','test'));
 const settings=JSON.parse(db.prepare('SELECT data_json FROM company_settings WHERE id=1').get().data_json);
 settings.productHierarchy=model.seed(fixtures);
 db.prepare('UPDATE company_settings SET data_json=? WHERE id=1').run(JSON.stringify(settings));
 db.prepare('INSERT INTO quotations (id,created_at,updated_at) VALUES (?,?,?)').run('history','test','test');
 db.prepare('INSERT INTO quotation_items (id,quotation_id,product_id,product_snapshot_json,price_snapshot_json,created_at,updated_at) VALUES (?,?,?,?,?,?,?)').run('item','history','remove',JSON.stringify(fixtures[1]),'{"price":123}','test','test');
 const historyBefore=db.prepare('SELECT * FROM quotation_items').all();
 const service=createClassificationDeletion({db,backupDir:path.join(process.env.QUOTE_DATA_DIR,'backups')});
 const target=settings.productHierarchy.nodes.find(n=>n.label==='待核对类型').id;
 const plan=service.inspect(target);
 assert.equal(plan.categoryCount,3);assert.deepEqual(plan.productIds,['remove']);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM products').get().n,2,'preview/cancel do not delete');
 insert.run('unrelated','挖掘机','CAT','330','{}','test','test');
 await assert.rejects(service.execute(target,plan.token),e=>e.status===409);
 const fresh=service.inspect(target);
 const blocked=createClassificationDeletion({db,backupDir:__filename});
 await assert.rejects(blocked.execute(target,fresh.token));
 assert(db.prepare('SELECT id FROM products WHERE id=?').get('remove'),'failed backup must leave products');
 const result=await service.execute(target,fresh.token);
 assert(fs.existsSync(result.backupPath));assert.equal(result.productCount,1);
 assert.deepEqual(db.prepare('SELECT id FROM products ORDER BY id').all().map(p=>p.id),['keep','unrelated']);
 assert.deepEqual(db.prepare('SELECT * FROM quotation_items').all(),historyBefore,'history snapshot unchanged');
 assert.equal(model.children(result.settings.productHierarchy).some(n=>n.label==='待核对类型'),false);
 const reconciled=model.reconcile(result.settings.productHierarchy,fixtures);
 assert.equal(reconciled.nodes.filter(n=>n.label==='待核对类型'&&!n.deletedAt).length,0,'no recreation from stale product cache');
 assert.deepEqual(model.resolve(reconciled,fixtures[1]),[]);
 const Database=require('better-sqlite3'),backup=new Database(result.backupPath,{readonly:true});
 assert.equal(backup.prepare('SELECT COUNT(*) AS n FROM products').get().n,3);backup.close();
 console.log('PASS: preview/cancel, stale confirmation, backup failure, cascade, history, cache protection, restorable full backup');
 db.close();app.exit(0);
}).catch(e=>{console.error(e);app.exit(1);});
