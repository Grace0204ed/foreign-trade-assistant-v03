const assert=require('node:assert/strict');
const schema=require('../assets/product-schema');
const settings={templates:[{fields:[{fieldKey:'custom_purity',zh:'纯度',fieldType:'text',sortOrder:80}]}]};
const original=structuredClone(settings.templates);
const data=schema.ensure(settings);
assert.equal(data.fields.length,8);
assert.deepEqual(settings.templates,original,'legacy templates remain available to history');
assert.equal(schema.ensure(settings),data,'initialization is idempotent');
data.fields.find(f=>f.fieldKey==='model').visible=false;
assert(!schema.fields(settings).some(f=>f.fieldKey==='model'));
const product={model:'M1',specificPrice:0,values:{model:'M2',custom_purity:'99%'}};
assert.equal(schema.value(product,'model'),'M2');
assert.equal(schema.value(product,'unitPrice'),0);
assert.equal(schema.value({specificPrice:'',values:{unitPrice:'100–200'}},'unitPrice'),'100–200');
assert.equal(schema.value(product,'custom_purity'),'99%');
const specs=schema.specifications(settings,'machinery');
specs[0].zh='功率测试';
assert.equal(schema.specifications(settings,'machinery')[0].zh,'功率测试');
assert.equal(schema.specifications(settings,'paint')[0].zh,'额定功率','type-specific configuration is independent');
assert.equal(product.values.model,'M2','hiding a field never removes existing values');
console.log('PASS unified product schema, idempotent migration, independent specifications, legacy preservation, zero and ranges');
